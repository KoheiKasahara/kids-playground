// ---------------------------------------------------------------------------
// シミュレーション全体
// ---------------------------------------------------------------------------

/**
 * 実寸より強い重力。
 * 弱くすると崩れた積み木がふわふわ落ちて「ガラガラ」感が出ないため、
 * 現実の9.8ではなく16を使い、崩壊のテンポを速くしている。
 */
export const GRAVITY_Y = -16

/**
 * 物理の固定タイムステップ。
 *
 * 最大発射速度(LAUNCH_SPEED_MAX = 33m/s)では1ステップの移動距離が
 * 33/180 ≒ 0.18m になる。積み木の最小厚み(0.3m)より十分小さく、
 * CCDと合わせて高速のまますり抜けないようにするための値。
 * ここを粗くする（1/60等）と、速い球が積み木を貫通して素通りする。
 *
 * ちいさいだま(launchSpeedScale 1.32、最大約43.6m/s)はこの値だけでは
 * 足りない移動距離になるため、すり抜け対策はタイムステップではなく
 * 玉のCCD（bowlingWorld.ts の setCcdEnabled / setSoftCcdPrediction）が主役。
 * そちらは速度に関係なく毎ステップ掃引判定するため、玉が速くなっても効く。
 */
export const PHYSICS_TIMESTEP = 1 / 180

/** 1フレームあたりの物理ステップ上限。低速端末で遅延が雪だるま式に増えないようにする。 */
export const MAX_PHYSICS_SUBSTEPS = 6

/** タブ復帰などの巨大な時間跳躍をそのまま物理へ渡さない。 */
export const MAX_FRAME_DELTA_MS = 100

// ---------------------------------------------------------------------------
// レーン（地面）
// ---------------------------------------------------------------------------

/**
 * レーンのごく緩い下り勾配[rad]。約3.1度。
 *
 * 「坂で加速させる」ためではなく、発射時点の初速を失いにくくするための保険。
 * 実際の勢いはLAUNCH_SPEED_MIN/MAXが決めている。
 * これ以上急にすると、置いただけの積み木が自重で滑り始める。
 * （静止摩擦の目安 tan(3.1°) ≒ 0.055 << 積み木同士の摩擦 0.42）
 */
export const LANE_SLOPE_RAD = 0.055

/** レーンの摩擦。玉の摩擦と平均されるため、単体では低めに見える値にしてある。 */
export const LANE_FRICTION = 0.16
/** レーンの反発。着地でぽんぽん跳ねないよう、ほぼ殺している。 */
export const LANE_RESTITUTION = 0.05

/** 横の縁と奥の壁。飛んだ玉と積み木が画面外へ消え続けないようにする。 */
export const RAIL_FRICTION = 0.25
export const RAIL_RESTITUTION = 0.1

// ---------------------------------------------------------------------------
// 積み木
// ---------------------------------------------------------------------------

/**
 * 積み木の密度。標準の柱(0.3 x 1.0 x 0.3)でおよそ0.20kgになる。
 *
 * どっしりだま(約4.9kg)との質量比はおよそ25:1。
 * この比があるおかげで、玉は1個目に当たった時点でほとんど減速せず、
 * 積み木の側だけが大きく吹き飛ぶ（＝1個だけ動いて終わらない）。
 * ここを上げると玉が止まりやすくなり、崩壊が地味になる。
 */
export const BLOCK_DENSITY = 2.2

/**
 * 積み木同士・積み木とレーンの摩擦。
 * 低すぎると初期状態で自然に滑り崩れ、高すぎると当たっても塔が動かない。
 */
export const BLOCK_FRICTION = 0.42

/** 積み木の反発。少しだけ弾ませて、当たった瞬間の散り方を派手にする。 */
export const BLOCK_RESTITUTION = 0.12

/** 積み木の減衰。ほぼ0にして、吹き飛んだ勢いが空中で急に消えないようにする。 */
export const BLOCK_LINEAR_DAMPING = 0.02
export const BLOCK_ANGULAR_DAMPING = 0.05

/** 崩れ切った積み木が細かく震え続けないよう、静止したものはsleepさせる。 */
export const BLOCK_CAN_SLEEP = true

// ---------------------------------------------------------------------------
// 発射（スリングショット）
// ---------------------------------------------------------------------------

/**
 * 最小・最大の発射速度[m/s]。
 *
 * 積み木までおよそ27mあるので、最大33m/sなら到達までおよそ0.8秒。
 * 画面上では弾道がしっかり見える「ビューン」になる。
 * 最小でも16m/sあり、弱い発射でも「コロコロ……」にはならない。
 * 弱・中・強の差は体感できるが、最弱でも積み木までは確実に届く。
 *
 * 助走距離を伸ばしたときも、ここは下げない。
 * 「離した瞬間の速さ」がこのゲームの気持ちよさそのものなので、
 * 距離の調整は発射位置（下のLAUNCH_Z）で行う。
 */
export const LAUNCH_SPEED_MIN = 16
export const LAUNCH_SPEED_MAX = 33

/**
 * 発射の高さ（弾道の山なり具合）。幼児にも分かる3段階。
 *
 * ドラッグ操作（狙う向き・パワー）とは完全に独立した設定値で、
 * 別UIで選ぶ（bowlingLaunch.ts の launchDirection/launchVelocity が使う）。
 *
 * pitchRad は仰角[rad]。正で上向き、負で下向き。
 * speedScale は発射速度への追加倍率（1.0が基準。launchSpeedの後にここで掛ける）。
 *
 * - ひくい: はっきり下向きに撃ち出し、早めに床へ着いて転がる／低くはずむ弾道にする。
 * - ふつう: 標準的な放物線。積み木までの距離が伸びた（LAUNCH_Z=20）ぶん、
 *   Phase 1〜4のように下向きのままだと最弱〜最速のどの玉も途中で失速して
 *   積み木の手前で転がるだけになってしまう（実測で確認した）。
 *   ここをわずかに上向きへ変えることで、速度・重力・発射位置は一切変えずに
 *   「山なりに飛んで積み木へ届く」を取り戻している。
 * - たかい: はっきり上向きに撃ち出し、山なりに長く滞空する弾道にする。上向きの角度だけで
 *   強い力いっぱいに引くと、放物線の距離(∝速度の2乗)が伸びすぎて積み木の頭上を
 *   通り過ぎてしまう（実測で確認した）。speedScaleをここだけ下げ、「たかいを選ぶと
 *   ゆっくり大きく山なりに飛ぶ」という体感そのものを速度側からも作りつつ、
 *   引く強さを変えても積み木の近くへ落ちやすくしてある。
 */
export type LaunchHeightLevel = 'low' | 'normal' | 'high'

export const LAUNCH_HEIGHT_LEVELS: readonly LaunchHeightLevel[] = ['low', 'normal', 'high']

export const DEFAULT_LAUNCH_HEIGHT_LEVEL: LaunchHeightLevel = 'normal'

export type LaunchHeightConfig = {
  pitchRad: number
  speedScale: number
}

export const LAUNCH_HEIGHT_CONFIG: Record<LaunchHeightLevel, LaunchHeightConfig> = {
  low: { pitchRad: -0.22, speedScale: 1 },
  normal: { pitchRad: 0.05, speedScale: 1 },
  high: { pitchRad: 0.24, speedScale: 0.7 },
}

/**
 * 左右の振れ幅の上限[rad]。約4.8度。
 *
 * 幼児に精密なエイムを求めないため、左右はここまでに制限する。
 * 積み木までの距離が伸びたぶん、同じ振れ幅では狙いが大きく外れて
 * 何も起きない投球が増えてしまうため、以前と同じ「積み木までおよそ±2mぶん動く」
 * 広さになるよう角度を狭めてある。塔の幅(約4.2m)の端を狙えるが、
 * 完全に外して何も起きない投球にはならない広さ。
 */
export const LAUNCH_YAW_LIMIT_RAD = 0.075

/** 発射位置（レーン面からの高さ）。積み木の最上段(約2.7m)より少し高い。 */
export const LAUNCH_HEIGHT = 2.9

/**
 * 発射位置のレーン方向の座標。負の向き(-Z)が積み木側。
 *
 * 発射地点と積み木の距離が近すぎると、離した瞬間にもう当たっていて
 * 「ビューンと進んでからドカン」の助走や、はずむだまのバウンドを
 * 味わう間がない（実画面で確認した）。積み木側の位置は一切動かさず、
 * 発射位置だけを大きく手前へ下げることで、距離を約1.9倍（約14m→約27m）にしてある。
 */
export const LAUNCH_Z = 20

/** ドラッグでスリングショットを引くときの、玉の最大移動距離[m]。 */
export const LAUNCH_PULL_MAX = 0.9

