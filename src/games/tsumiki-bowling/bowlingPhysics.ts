/**
 * 玉の速度上限。発射直後の最大速度より少しだけ上に置く。
 *
 * ちいさいだまは launchSpeedScale で最大 33 * 1.32 ≒ 43.6m/s まで出るため、
 * ここが低いと「3種類で最速」のはずの玉が発射直後にクランプされてしまう。
 */
export const MAX_BALL_SPEED = 46
/** 積み木の速度上限。爆発的に吹き飛んでも画面外の彼方までは行かせない。 */
export const MAX_BLOCK_SPEED = 26
/** 角速度の上限。数値が暴れて表示が壊れるのを防ぐ。 */
export const MAX_ANGULAR_SPEED = 60

/** これより下に落ちたものは場外扱いにする（レーンの外へ落ちた玉・積み木）。 */
export const OUT_OF_BOUNDS_Y = -6
