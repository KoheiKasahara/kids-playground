/**
 * ベルトの上にいる間、毎物理ステップ加える力[N]。
 *
 * applyImpulse(force * dt) をそのまま各Bodyへ渡すだけなので、質量の重いタイプほど
 * 速度変化が小さく、軽いタイプほど大きくなる（F=ma）。既存の質量差を追加のスケーリング
 * なしで自然に活かせる。
 * 標準的な周回速度でベルトの全長(halfLength*2 ≒ 1.7m)を通過するのに要する
 * 0.5〜1秒ほどの滞在では、速度変化がおよそ0.3〜0.6m/s程度に収まる大きさにしてある。
 * 乗った瞬間に吹き飛ぶ強さではなく、通過するにつれて軌道が少しずつずれる強さを狙っている。
 */
export const KOMA_BELT_FORCE = 0.16

