/**
 * コマバトルの物理パラメータを1か所へ集めたファイル。
 *
 * 数値をエンジン本体へ直接書かず、必ずここから読む。
 * 「なぜその値なのか」をコメントで残し、後続Phaseで調整するときに
 * 触ってよい値と触ると壊れる値が分かるようにしている。
 */

/**
 * 実寸より強い重力を使う。コマがすり鉢を滑って中央へ寄る速さと、
 * 失速後に倒れ切るテンポの両方がこの値で決まる。
 */
export const GRAVITY_Y = -14

/** 先端(半径0.055)の接触を安定させるため、描画フレームより細かい120Hzで積分する。 */
export const PHYSICS_TIMESTEP = 1 / 120

/** 1フレームあたりの物理ステップ上限。低速端末で処理落ちが雪だるま式に増えないようにする。 */
export const MAX_PHYSICS_SUBSTEPS = 4

/** タブ復帰などの巨大な時間跳躍をそのまま物理へ渡さない。 */
export const MAX_FRAME_DELTA_MS = 100

// ---------------------------------------------------------------------------
// コマの形状。見た目Meshもこの寸法を共有するが、物理Colliderは下の3つだけを使う。
// ---------------------------------------------------------------------------

/** 接地する先端。点接触に近い球にして、ねじれ摩擦で回転が不自然に止まらないようにする。 */
export const TIP_RADIUS = 0.055

/** 円盤部（相手とぶつかる本体）。 */
export const DISK_RADIUS = 0.3
export const DISK_HALF_HEIGHT = 0.045
/** 先端の接地点をローカル原点とし、そこから円盤中心までの高さ。重心の高さをほぼ決める。 */
export const DISK_CENTER_Y = 0.28

/** 軸。先端と円盤をつなぐ細い円柱で、傾いたコマ同士がすり抜けるのを防ぐ。 */
export const SHAFT_RADIUS = 0.05
export const SHAFT_HALF_HEIGHT = 0.115
export const SHAFT_CENTER_Y = 0.17

/**
 * 密度。3つのColliderに同じ値を使い、合計約0.22kgになる。
 *
 * 挙動を決めるのは質量そのものではなく「重心の高さ(約0.27)と円盤の慣性モーメントの比」で、
 * この寸法では自転が約28rad/sを下回るとジャイロ効果で自立できなくなる。
 * 3つを同じ密度に保ったまま全体を増減させても、この比は変わらない。
 */
export const KOMA_DENSITY = 8

/**
 * 先端と床。
 *
 * Rapierは接触する2つのColliderの摩擦を平均して使う。
 * 実際に効くのは (TIP_FRICTION + FLOOR_FRICTION) / 2 なので、
 * 高速回転中のコマがすり鉢の上をよく滑るよう、両方を小さくしている。
 * ここを上げると、まわり始めて1秒でコマが止まってしまう。
 */
export const TIP_FRICTION = 0.01
export const TIP_RESTITUTION = 0.05

/**
 * 円盤部の摩擦。先端と違って高くしてある。
 *
 * 逆回転どうしの円盤が触れたとき、回転を弾き合う力へ変える役目と、
 * 倒れたコマが床を滑り続けずに止まる役目を兼ねる。
 */
export const DISK_FRICTION = 0.35
export const DISK_RESTITUTION = 0.6

/** すり鉢の床。上のTIP_FRICTIONと平均されるため、単体で見ると低めの値になる。 */
export const FLOOR_FRICTION = 0.015
export const FLOOR_RESTITUTION = 0.05

/** 外周壁。跳ね返りを弱くして、壁際でいつまでも跳ね回らないようにする。 */
export const WALL_FRICTION = 0.25
export const WALL_RESTITUTION = 0.2

/**
 * 回転の減衰。回転エネルギーの低下はこの指数減衰が主役で、
 * ここを手で書き換えて「それらしく見せる」処理はどこにも置いていない。
 * この形のコマは、自転が約28rad/sを下回るとジャイロ効果だけでは自立できなくなる。
 * 0.11 は初速75rad/sからそこまで約9秒かかる値（ln(75/28)/0.11）で、
 * ぐらつき始めてから倒れ切るまでを足すと1試合およそ10〜12秒になる。
 * これより小さくすると、high speedのまま何もしない時間が長く続いて退屈になる。
 */
export const ANGULAR_DAMPING = 0.11

/**
 * 並進の減衰。小さめにして、序盤はすり鉢の斜面を周回し続けられるようにする。
 * 倒れたコマは円盤部の高い摩擦（DISK_FRICTION）で止まるので、ここは効かせなくてよい。
 */
export const LINEAR_DAMPING = 0.02

// ---------------------------------------------------------------------------
// 発射
// ---------------------------------------------------------------------------

/** 開始時の自転速度[rad/s]。自立限界(約28rad/s)より十分速い値から始める。 */
export const START_SPIN_SPEED = 75

/** 開始位置の中心からの距離。 */
export const START_RADIUS = 1.9

/**
 * 開始時の周回速度[m/s]。
 *
 * 斜面が向心力になるため、START_RADIUSで釣り合う速度はおよそ2.24。
 * それより少し速くして、開始直後は外周壁ぎわをまわり、
 * 失速に従って谷（VALLEY_RADIUS）へ寄っていくようにしている。
 * 2個を逆向きにまわすことで半周ごとにすれ違い、確実に何度もぶつかる。
 */
export const START_ORBIT_SPEED = 2.55

/** 周回に少しだけ内向き成分を足し、外周に貼り付いたまま終わらないようにする。 */
export const START_INWARD_SPEED = 0.15

// ---------------------------------------------------------------------------
// 安全域。NaNや宇宙まで吹き飛ぶ挙動を常態化させないための上限。
// ---------------------------------------------------------------------------

/** これを超える並進速度は上限へ丸める。 */
export const MAX_LINEAR_SPEED = 9
/** これを超える角速度は上限へ丸める。 */
export const MAX_ANGULAR_SPEED = 90

/**
 * 1試合ごとの初速のばらつき（±の割合）。
 *
 * 2個がまったく同じ条件だと同じ瞬間に倒れて引き分けばかりになるため、
 * 「まわし方に少し差が出る」ぶんだけ初速を散らす。
 * 0.09なら倒れる時刻に十分な差がつき、引き分けばかりにならない。
 * コマの種類ごとの能力差ではないので、KomaSpecには持たせない。
 */
export const START_SPIN_VARIANCE = 0.09

/** ここまで落ちたら場外扱い。壁を越えたコマは高さ場の外なので落下し続ける。 */
export const OUT_FLOOR_Y = -1.2
