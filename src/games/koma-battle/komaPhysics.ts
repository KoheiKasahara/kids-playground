/** 開始時の自転速度[rad/s]。自立限界(約28rad/s)より十分速い値から始める。 */
export const START_SPIN_SPEED = 84

/** 開始位置の中心からの距離。 */
export const START_RADIUS = 1.9

/**
 * 開始時の周回速度[m/s]。
 *
 * 斜面が向心力になるため、START_RADIUSで釣り合う速度はおよそ2.24。
 * それより十分速くして、開始直後は外周壁ぎわをまわり、
 * 失速に従って谷（VALLEY_RADIUS）へ寄っていくようにしている。
 * 2個を逆向きにまわすことで半周ごとにすれ違い、確実に何度もぶつかる。
 */
export const START_ORBIT_SPEED = 2.75

/** 周回に内向き成分を足し、開始直後から中央へも動き始めるようにする。 */
export const START_INWARD_SPEED = 0.18

